/**
 * Generates the parts of the documentation that must not drift from the code:
 *
 *     docs/07-reference.md    every element, argument, property and event
 *     docs/05-diagnostics.md  every diagnostic code
 *     docs/11-todo.md         the roadmap, rendered from `src/tooling/todo.ts`
 *
 *     npm run docs:ref          # rewrite the files
 *     npm run docs:ref -- --check   # fail if they are out of date (used by tests and CI)
 */

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { CODES } from '../src/analysis/diagnostics.ts';
import { PHASES, TODO, progressOf, type TodoItem, type TodoStatus } from '../src/tooling/todo.ts';
import { BUILTIN_STYLES, STYLE_PROPS, STYLE_SURFACE_PROPS } from '../src/analysis/styles.ts';
import {
  GENERIC_EVENTS,
  UNIVERSAL_PROPS,
  WIDGETS,
  eventsFor,
  propsFor,
  widgetsByGroup,
  type PropSpec,
  type WidgetSpec,
} from '../src/analysis/widgets/registry.ts';

const HEADER = (title: string, command: string): string =>
  [
    `# ${title}`,
    '',
    '<!-- Generated by `npm run docs:ref` from the compiler sources. Do not edit by hand. -->',
    '',
    `Regenerate with \`${command}\`; \`tests/registry.test.ts\` fails when this file is stale.`,
    '',
    '',
  ].join('\n');

function propRow(prop: PropSpec): string {
  const kind = prop.kind === 'enum' ? `one of ${prop.values?.map((value) => `\`${value}\``).join(', ')}` : `\`${prop.kind}\``;
  const maps = prop.mapsTo === undefined ? '' : ` → \`${prop.mapsTo}\``;
  return `| \`${prop.name}\` | ${kind} | ${prop.summary}${maps} |`;
}

const PROP_TABLE_HEAD = ['| Property | Kind | Meaning |', '| --- | --- | --- |'].join('\n');

function widgetSection(spec: WidgetSpec): string {
  const lines: string[] = [];
  const args = spec.args.length === 0 ? 'no arguments' : spec.args.map((arg) => `\`${arg.name}: ${arg.kind}\``).join(', ');
  const children = { multi: 'any number of children', single: 'exactly one child', none: 'no children' }[spec.children];

  lines.push(`### \`${spec.tag}\``);
  lines.push('');
  lines.push(spec.summary);
  lines.push('');
  lines.push(`- **Arguments:** ${args}`);
  lines.push(`- **Children:** ${children}`);
  lines.push(`- **Events:** ${[...eventsFor(spec)].join(', ')}`);
  if (spec.note !== undefined) lines.push(`- **Note:** ${spec.note}`);
  lines.push('');

  const own = spec.props.filter((prop) => !UNIVERSAL_PROPS.some((universal) => universal.name === prop.name));
  if (own.length > 0) {
    lines.push('| Property | Kind | Meaning |');
    lines.push('| --- | --- | --- |');
    for (const prop of spec.props) lines.push(propRow(prop));
    lines.push('');
  }

  lines.push('```plainui');
  lines.push(spec.example);
  lines.push('```');
  lines.push('');
  return lines.join('\n');
}

export function renderReference(): string {
  const lines: string[] = [HEADER('Element reference', 'npm run docs:ref')];

  lines.push('## How to read this page');
  lines.push('');
  lines.push(
    'Lowercase names are built-in elements. A Capitalised name is either a `component` declared in a',
    '`.pui` file or a host Dart widget constructor; components take the parameters they declare, host',
    'widgets take whatever their constructor takes.',
  );
  lines.push('');

  lines.push('## Properties every element accepts');
  lines.push('');
  lines.push('These are implemented by wrapping the element, so they work on both built-ins and component call sites.');
  lines.push('');
  lines.push(PROP_TABLE_HEAD);
  for (const prop of UNIVERSAL_PROPS) lines.push(propRow(prop));
  lines.push('');

  lines.push('## Gestures every element accepts');
  lines.push('');
  lines.push(
    `\`${GENERIC_EVENTS.join('`, `')}\` — written as \`on tap:\` with an indented block of actions, like any native event.`,
  );
  lines.push('');

  for (const group of widgetsByGroup()) {
    lines.push(`## ${group.group[0]!.toUpperCase()}${group.group.slice(1)}`);
    lines.push('');
    for (const spec of group.specs) lines.push(widgetSection(spec));
  }

  lines.push('## Styles');
  lines.push('');
  lines.push(`Built-in text styles: ${BUILTIN_STYLES.map((name) => `\`${name}\``).join(', ')}.`);
  lines.push('');
  lines.push('A `style` declaration bundles properties, and `style=` applies it to any element:');
  lines.push('');
  lines.push('```plainui');
  lines.push('style panel:');
  lines.push('    background=surface');
  lines.push('    radius=card');
  lines.push('    padding=md');
  lines.push('    shadow=soft');
  lines.push('');
  lines.push('style price:');
  lines.push('    size=20');
  lines.push('    weight=bold');
  lines.push('');
  lines.push('screen Home:');
  lines.push('    card style=panel:');
  lines.push('        text "10 ETB" style=price');
  lines.push('```');
  lines.push('');
  lines.push(`**Text properties** — how drawn text looks: ${STYLE_PROPS.map((name) => `\`${name}\``).join(', ')}.`);
  lines.push('They only mean something on `text`, `button` and `input`; applying a style that sets them to any');
  lines.push('other element is an error (`PUI2373`).');
  lines.push('');
  lines.push(`**Surface properties** — how the element itself is painted and spaced: ${STYLE_SURFACE_PROPS.map((name) => `\`${name}\``).join(', ')}.`);
  lines.push('These work on every element, because the language applies them by wrapping the element.');
  lines.push('');
  lines.push('**Not stylable:** `main`, `cross`, `gap`, `align`, `expand` and `flex`. Those describe how a');
  lines.push('layout is arranged, not how it looks; a style that rearranged a layout would be a breakpoint by');
  lines.push('another name (§ responsive composition).');
  lines.push('');
  lines.push('Precedence is one line: **property on the element > property from the style > target default**.');
  lines.push('There is no cascade and no inheritance — `text "x" style=price size=12` overrides the style.');
  lines.push('');

  return lines.join('\n');
}

const CATEGORY_TITLES: Record<string, string> = {
  '10': 'Lexical and structural',
  '20': 'Names, elements and properties',
  '22': 'Types',
  '23': 'Styles and bindings',
  '24': 'Warnings about intent',
  '30': 'Project',
  '31': 'Cross-file',
  '40': 'Command line',
};

export function renderDiagnostics(): string {
  const lines: string[] = [HEADER('Diagnostic reference', 'npm run docs:ref')];

  lines.push('Every diagnostic is a structured value with a stable code, a severity, a span in the source, an');
  lines.push('optional hint and optional related locations. `plainui explain <code>` prints one entry;');
  lines.push('`plainui check --json` prints them as JSON lines for editors and CI.');
  lines.push('');
  lines.push('| Code | Severity | Title |');
  lines.push('| --- | --- | --- |');
  for (const [code, info] of Object.entries(CODES)) {
    lines.push(`| [\`${code}\`](#${code.toLowerCase()}) | ${severityOf(code)} | ${info.title} |`);
  }
  lines.push('');

  let category = '';
  for (const [code, info] of Object.entries(CODES)) {
    const key = code.slice(3, 5);
    if (key !== category) {
      category = key;
      lines.push(`## ${CATEGORY_TITLES[key] ?? 'Other'}`);
      lines.push('');
    }
    lines.push(`### ${code}`);
    lines.push('');
    lines.push(`**${info.title}** — ${severityOf(code)}`);
    lines.push('');
    lines.push(info.description);
    lines.push('');
    if (info.fix !== undefined) {
      lines.push(`*Fix:* ${info.fix}`);
      lines.push('');
    }
  }
  return lines.join('\n');
}

/** Codes the command line raises directly; they are not produced by the compiler pipeline. */
const CLI_CODES = new Set(['PUI3003', 'PUI4001', 'PUI4002', 'PUI4003']);

/**
 * Severity is declared in the catalogue, so this is a plain lookup. The compiler is checked
 * against it by `tests/registry.test.ts`, which compares the severity at each call site.
 */
function severityOf(code: string): string {
  return (CODES as Record<string, { severity?: string }>)[code]?.severity ?? 'error';
}

/** Code → the severities the compiler actually reports it with, read from the sources. */
export function severitiesInSource(): Map<string, Set<string>> {
  const map = new Map<string, Set<string>>();
  const root = join(fileURLToPath(new URL('../src/', import.meta.url)));

  const visit = (directory: string): void => {
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      const full = join(directory, entry.name);
      if (entry.isDirectory()) {
        visit(full);
        continue;
      }
      if (!entry.name.endsWith('.ts')) continue;
      const text = readFileSync(full, 'utf8');
      for (const match of text.matchAll(/this\.(error|warning|info)\(\s*'([A-Z0-9]+)'/g)) {
        const set = map.get(match[2]!) ?? new Set<string>();
        set.add(match[1]!);
        map.set(match[2]!, set);
      }
      // `code: 'PUI4001'` in a failure object, and `fail('PUI4001', …)` in the CLI: both are places a
      // catalogue entry is raised without going through the diagnostic bag.
      for (const match of text.matchAll(/(?:code:\s*'|fail\(\s*')(PUI\d{4})'/g)) {
        const set = map.get(match[1]!) ?? new Set<string>();
        set.add('error');
        map.set(match[1]!, set);
      }
    }
  };

  visit(root);
  for (const code of CLI_CODES) map.set(code, new Set(['error']));
  return map;
}

const STATUS_MARK: Record<TodoStatus, string> = { done: '✔', next: '▸', todo: '·' };

function todoRow(item: TodoItem): string {
  const mark = STATUS_MARK[item.status];
  const title =
    item.status === 'next' ? `**${item.title}**` : item.status === 'done' ? `~~${item.title}~~` : item.title;
  return `| ${mark} | ${title} | \`${item.size}\` | ${item.acceptance} |`;
}

/**
 * The roadmap page. Everything between the generated markers comes from `src/tooling/todo.ts`, so a
 * phase cannot be "finished" in prose while the table says otherwise.
 */
export function renderTodo(): string {
  const lines: string[] = [HEADER('Todo and decisions', 'npm run docs:ref')];

  lines.push('This page is rendered from `src/tooling/todo.ts`. `plainui next` prints the same table,');
  lines.push('`plainui next --json` prints it for a script. `tests/todo.test.ts` refuses an item that has no');
  lines.push('acceptance criterion, an unknown size, or a phase that does not exist.');
  lines.push('');

  const current = TODO.find((item) => item.status === 'next') ?? TODO.find((item) => item.status === 'todo');
  if (current !== undefined) {
    lines.push(`**Now:** ${current.title} (\`${current.id}\`, ${current.size}) — ${current.acceptance}`);
    lines.push('');
  }

  for (const phase of PHASES) {
    const { done, total } = progressOf(phase.id);
    lines.push(`## ${phase.title} — ${done}/${total}`);
    lines.push('');
    if (phase.gate !== undefined) {
      lines.push(`*Gate to leave this phase:* ${phase.gate}`);
      lines.push('');
    }
    lines.push('| | Item | Size | Acceptance |');
    lines.push('| --- | --- | --- | --- |');
    for (const item of TODO.filter((entry) => entry.phase === phase.id)) lines.push(todoRow(item));
    lines.push('');
  }

  lines.push('## Why these, in this order');
  lines.push('');
  lines.push(
    'The phase gate in `docs/09-vision.md` is what decides the order, not preference: the language model',
    '(`state`, `derived`, `effect`, `task`) has to be settled, and one target has to be genuinely deep,',
    'before a second target can be judged a faithful lowering rather than a translation table.',
  );
  lines.push('');
  return lines.join('\n');
}

const TARGETS = [
  { path: 'docs/07-reference.md', render: renderReference },
  { path: 'docs/05-diagnostics.md', render: renderDiagnostics },
  { path: 'docs/11-todo.md', render: renderTodo },
];

const check = process.argv.includes('--check');
let stale = 0;

for (const target of TARGETS) {
  const expected = target.render();
  let current: string | undefined;
  try {
    current = readFileSync(target.path, 'utf8');
  } catch {
    current = undefined;
  }

  if (current === expected) {
    console.log(`ok      ${target.path}`);
    continue;
  }
  if (check) {
    stale += 1;
    console.error(`stale   ${target.path} — run npm run docs:ref`);
    continue;
  }
  writeFileSync(target.path, expected, 'utf8');
  console.log(`wrote   ${target.path}`);
}

if (stale > 0) process.exit(1);

export const widgetCount = WIDGETS.size;
